"""Frozen evaluation protocol: probe-based cold start for a new video-generation arm + budgeted routing.

Do not edit this file when developing a method; methods live in harness/methods/.

Data layout (under data_dir):
  prompts.csv          prompt_id, split (train/dev), text, ... (other columns are free: source, dims, group)
  arms.csv             arm, family, config, usd_per_clip, heldout (0/1)
  labels.csv           prompt_id, arm, seed, target, [dim_* columns]; target is the frozen quality score
                       (higher is better)
  features/<name>.npy  prompt features, rows aligned with prompts.csv

Protocol:
  Every non-held-out arm takes a turn as the "new arm" m*. The other arms have all labels on train prompts;
  m* only has labels on the K train prompts (probes) chosen by the method. On eval prompts we route with
  argmax(q_hat - lambda * c) over (known-arm predictions U m* prediction), trace the cost-quality frontier with
  the true target, subtract the single-arm hull (proportional mixing, prompt-agnostic) and average over
  N_BUDGETS budget points.
  full    = m* labelled on all train prompts (upper bound); exclude = m* unavailable (lower bound).
  recovery = (method - exclude) / (full - exclude), averaged over arms with full - exclude > ROOM_MIN.
  probe_cost = number of probes x price of m*, reported separately.
"""
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.linear_model import RidgeCV

LAMBDAS = np.concatenate([[0], np.logspace(-3, 2, 160)])
N_BUDGETS = 8
ROOM_MIN = 0.003
KS = [10, 20, 50]


@dataclass
class Data:
    prompts: pd.DataFrame
    arms: pd.DataFrame
    Q: np.ndarray                    # (n_prompt, n_arm) seed-averaged target, NaN if missing
    D: np.ndarray                    # (n_prompt, n_arm, n_dim) seed-averaged dimension scores
    dims: list
    feats: dict
    noise_sd: np.ndarray = None      # (n_arm,) target s.d. across seeds of the same prompt (if multi-seed)


@dataclass
class Ctx:
    """What a method gets to see. Contains no label of m* on any prompt (probe labels are passed separately)."""
    train: np.ndarray                # row indices of train prompts in Data
    eval: np.ndarray
    feats_train: dict
    feats_eval: dict
    text_train: list
    text_eval: list
    known_arms: pd.DataFrame
    star_arm: pd.Series
    Q_known_train: np.ndarray        # (n_train, n_known)
    D_known_train: np.ndarray        # (n_train, n_known, n_dim)
    dims: list
    prompts_train: pd.DataFrame
    prompts_eval: pd.DataFrame
    extra: dict = field(default_factory=dict)


def load(data_dir):
    d = Path(data_dir)
    prompts = pd.read_csv(d / "prompts.csv")
    arms = pd.read_csv(d / "arms.csv")
    lab = pd.read_csv(d / "labels.csv")
    dims = [c for c in lab.columns if c.startswith("dim_")]
    pid = {p: i for i, p in enumerate(prompts.prompt_id)}
    aid = {a: i for i, a in enumerate(arms.arm)}
    lab = lab[lab.prompt_id.isin(pid) & lab.arm.isin(aid)]
    g = lab.groupby(["prompt_id", "arm"])
    m = g[["target"] + dims].mean().reset_index()
    Q = np.full((len(prompts), len(arms)), np.nan)
    D = np.full((len(prompts), len(arms), len(dims)), np.nan)
    pi, ai = m.prompt_id.map(pid).to_numpy(), m.arm.map(aid).to_numpy()
    Q[pi, ai] = m.target.to_numpy()
    if dims:
        D[pi, ai] = m[dims].to_numpy()
    sd = g.target.std().dropna()
    noise = sd.groupby(level="arm").mean().reindex(arms.arm).to_numpy() if len(sd) else None
    feats = {f.stem: np.load(f) for f in sorted((d / "features").glob("*.npy"))}
    for k, v in feats.items():
        assert len(v) == len(prompts), f"features/{k}.npy has {len(v)} rows, prompts.csv has {len(prompts)}"
    return Data(prompts, arms, Q, D, dims, feats, noise)


def hull_fn(cost, qual):
    pts = sorted(zip(cost, qual))
    hull = []
    for p in pts:
        if hull and p[1] <= hull[-1][1]:
            continue
        while len(hull) >= 2:
            (x1, y1), (x2, y2) = hull[-2], hull[-1]
            if (y2 - y1) * (p[0] - x1) <= (p[1] - y1) * (x2 - x1):
                hull.pop()
            else:
                break
        hull.append(p)
    hx, hy = np.array(hull).T
    return lambda b: np.interp(b, hx, hy, left=np.nan)


def frontier_gain(P, Y, c, budgets):
    """P: predicted quality (n, arm), -inf marks an unavailable arm; Y: true quality.
    Returns routed frontier minus single-arm hull at each budget."""
    rows = np.arange(len(Y))
    q = Y.mean(0)
    pts = []
    scale = np.ptp(q) / max(np.ptp(c), 1e-9)          # scale the lambda grid by quality span / cost span
    for lam in LAMBDAS * scale:
        ch = (P - lam * c).argmax(1)
        pts.append((c[ch].mean(), Y[rows, ch].mean()))
    pts = np.array(pts)
    f = hull_fn(np.r_[pts[:, 0], c], np.r_[pts[:, 1], q])
    h = hull_fn(c, q)
    return np.array([f(b) - h(b) for b in budgets])


def budgets_for(c):
    lo, hi = np.sort(c)[1] if len(c) > 2 else c.min(), c.max()
    return np.linspace(lo, hi, N_BUDGETS + 2)[1:-1]


def ridge(Xtr, Ytr, Xte):
    mu = np.nanmean(Ytr, 0)
    return RidgeCV(alphas=np.logspace(-1, 4, 11)).fit(Xtr, Ytr - mu).predict(Xte).reshape(len(Xte), -1) + mu


def default_X(feats, idx):
    return np.hstack([feats[k][idx] for k in sorted(feats)])
